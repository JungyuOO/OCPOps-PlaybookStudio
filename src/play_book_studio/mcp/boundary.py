"""Read-only MCP tool boundary for PBS.

This module intentionally avoids a runtime MCP dependency. It defines the tool
contract and deterministic local handlers so the later MCP transport can wrap
the same read-only behavior without changing tool semantics.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from play_book_studio.aiops.event_timeline import read_timeline_events


